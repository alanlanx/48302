export function assertQuestionBank() {
  const ids = new Set<string>();
  const counts: Record<Category, number> = { line: 0, ckhs: 0, taipei: 0 };
  for (const question of QUESTIONS) {
    if (ids.has(question.id)) throw new Error(`題目編號重複：${question.id}`);
    ids.add(question.id);
    if (question.options.length !== 4) throw new Error(`選項數量不對：${question.id}`);
    if (new Set(question.options).size !== 4) throw new Error(`選項重複：${question.id}`);
    if (question.correctIndex < 0 || question.correctIndex > 3) {
      throw new Error(`正解索引不對：${question.id}`);
    }
    if (!question.prompt.trim() || !question.explanation.trim()) {
      throw new Error(`題目或解析是空的：${question.id}`);
    }
    counts[question.category] += 1;
  }
  if (counts.line < 40) throw new Error("要運動歐題庫不足");
  if (counts.ckhs < 10) throw new Error("建中題庫不足");
  if (counts.taipei < 10) throw new Error("九零年代題庫不足");
  return counts;
}
